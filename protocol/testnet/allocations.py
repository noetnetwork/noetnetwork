"""Exact block-1 allocation outputs for the public testnet (noet-testnet-1).

Turns the monthly vesting schedule (economics/monthly_vesting.py) and the
testnet-only signer public keys into P2WSH outputs:

  <cltv height> OP_CHECKLOCKTIMEVERIFY OP_DROP OP_2 <k1> <k2> <k3> OP_3 OP_CHECKMULTISIG

with keys sorted (BIP67). The initial ecosystem grant has no time lock. The
node enforces these outputs, in this order, in block 1's coinbase.
"""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'economics'))
from monthly_vesting import installments  # noqa: E402
from tokenomics import ALLOCATION_ATOMS as TOTAL_ATOMS, ALLOCATIONS  # noqa: E402

OP_2, OP_3, OP_CHECKMULTISIG, OP_CLTV, OP_DROP = 0x52, 0x53, 0xae, 0xb1, 0x75
OUTPUTS = sum(a['months'] + (1 if a['initialCoins'] else 0) for a in ALLOCATIONS)


def script_number(value):
    """Minimal CScriptNum push for a positive height."""
    if value <= 0:
        raise ValueError('Lock heights must be positive')
    data = bytearray()
    while value:
        data.append(value & 0xff)
        value >>= 8
    if data[-1] & 0x80:
        data.append(0)
    return bytes([len(data)]) + bytes(data)


def multisig(keys):
    points = sorted(bytes.fromhex(k) for k in keys)
    if len(points) != 3 or len(set(points)) != 3 or any(len(p) != 33 or p[0] not in (2, 3) for p in points):
        raise ValueError('Each allocation needs three distinct compressed keys')
    return bytes([OP_2]) + b''.join(bytes([33]) + p for p in points) + bytes([OP_3, OP_CHECKMULTISIG])


CHARSET = 'qpzry9x8gf2tvdw0s3jn54khce6mua7l'


def _polymod(values):
    chk = 1
    for value in values:
        top = chk >> 25
        chk = (chk & 0x1ffffff) << 5 ^ value
        for i, gen in enumerate((0x3b6a57b2, 0x26508e6d, 0x1ea119fa, 0x3d4233dd, 0x2a1462b3)):
            chk ^= gen if (top >> i) & 1 else 0
    return chk


def segwit_v0_address(hrp, program):
    """BIP173 bech32 address for a version-0 witness program (20 or 32 bytes)."""
    if len(program) not in (20, 32):
        raise ValueError('Version-0 programs are 20 or 32 bytes')
    acc, bits, data = 0, 0, [0]
    for byte in program:
        acc, bits = (acc << 8) | byte, bits + 8
        while bits >= 5:
            bits -= 5
            data.append((acc >> bits) & 31)
    if bits:
        data.append((acc << (5 - bits)) & 31)
    expanded = [ord(c) >> 5 for c in hrp] + [0] + [ord(c) & 31 for c in hrp]
    mod = _polymod(expanded + data + [0] * 6) ^ 1
    return hrp + '1' + ''.join(CHARSET[d] for d in data + [(mod >> 5 * (5 - i)) & 31 for i in range(6)])


def vault_addresses(keys_path, hrp):
    """Each allocation class's 2-of-3 vault address without a time lock: the
    address a wallet shows for that vault, and where the initial ecosystem grant
    and any mining reward sent to the vault land."""
    classes = json.loads(Path(keys_path).read_text())['classes']
    return {name: segwit_v0_address(hrp, hashlib.sha256(multisig(keys)).digest())
            for name, keys in sorted(classes.items())}


def outputs(keys_path=ROOT / 'testnet/allocation-keys.json'):
    classes = json.loads(Path(keys_path).read_text())['classes']
    missing = sorted({a['name'] for a in ALLOCATIONS} - set(classes))
    if missing:
        raise ValueError(f'allocation-keys.json has no signers for: {", ".join(missing)} '
                         '(run testnet/set_allocation_keys.py)')
    rows = []
    for row in installments():
        custody = multisig(classes[row['allocation']])
        lock = row['cltvHeight']
        witness = custody if lock is None else script_number(lock) + bytes([OP_CLTV, OP_DROP]) + custody
        rows.append({**row, 'witnessScript': witness.hex(),
                     'scriptPubKey': '0020' + hashlib.sha256(witness).hexdigest()})
    if sum(int(r['amountAtoms']) for r in rows) != TOTAL_ATOMS or len(rows) != OUTPUTS:
        raise AssertionError(f'Allocations must conserve exactly {TOTAL_ATOMS} atoms in {OUTPUTS} outputs')
    return rows


def header(rows, namespace='testnet'):
    lines = [
        '// Generated by protocol/testnet/allocations.py. Do not edit by hand.',
        '#pragma once',
        '#include <array>',
        '#include <cstdint>',
        '#include <string_view>',
        f'namespace noet::{namespace} {{',
        'struct Allocation { std::string_view script_pub_key; std::int64_t atoms; };',
        f'inline constexpr std::array<Allocation, {len(rows)}> ALLOCATIONS{{{{',
    ]
    lines += [f'    {{"{r["scriptPubKey"]}", {r["amountAtoms"]}}},' for r in rows]
    lines += ['}};', f'inline constexpr std::int64_t ALLOCATION_TOTAL = {TOTAL_ATOMS};', f'}}  // namespace noet::{namespace}', '']
    return '\n'.join(lines)


def manifest(rows, network='noet-testnet-1'):
    """Public list the wallet uses to find the allocations a cosigner key controls."""
    return {'network': network, 'outputs': [
        {k: r[k] for k in ('allocation', 'installment', 'amountAtoms', 'cltvHeight', 'witnessScript', 'scriptPubKey')}
        for r in rows]}


MANIFEST = ROOT.parent / 'web/public/allocations/noet-testnet-1.json'

if __name__ == '__main__':
    if sys.argv[1:2] == ['--vault-addresses']:
        # allocations.py --vault-addresses KEYS_FILE HRP (noet for mainnet, tnoet for the testnet)
        print(json.dumps(vault_addresses(sys.argv[2], sys.argv[3]), indent=2))
        sys.exit(0)
    rows = outputs()
    if sys.argv[1:] == ['--write-manifest']:
        MANIFEST.parent.mkdir(exist_ok=True)
        MANIFEST.write_text(json.dumps(manifest(rows), separators=(',', ':')) + '\n')
        sys.exit(0)
    print(json.dumps({'outputs': len(rows), 'totalAtoms': str(sum(int(r['amountAtoms']) for r in rows)),
                      'first': rows[0], 'last': rows[-1]}, indent=2))
